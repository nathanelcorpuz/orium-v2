// Buckets rows by a derived key - used to group forecast rows / settlements
// per source item for views like Debt/Savings' upcoming+paid transactions.
export function groupBy<T>(rows: T[], keyOf: (row: T) => string): Map<string, T[]> {
  const map = new Map<string, T[]>();
  for (const row of rows) {
    const key = keyOf(row);
    const list = map.get(key) ?? [];
    list.push(row);
    map.set(key, list);
  }
  return map;
}
